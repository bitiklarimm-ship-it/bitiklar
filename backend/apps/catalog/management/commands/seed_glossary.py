class Command(BaseCommand):
    help = "Atamalar lug'atini boshlang'ich yozuvlar bilan to'ldiradi"

    def handle(self, *args, **opts):
        n = 0
        for key, group, uz, ru, en, orig, duz, dru, den in TERMS:
            _, created = Term.objects.get_or_create(key=key, defaults=dict(
                group=group, term_uz=uz, term_ru=ru, term_en=en, term_original=orig,
                definition_uz=duz, definition_ru=dru, definition_en=den,
            ))
            n += int(created)
        self.stdout.write(self.style.SUCCESS(f"Lug'at: {n} ta yangi atama qo'shildi"))
