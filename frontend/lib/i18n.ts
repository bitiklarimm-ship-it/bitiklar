export const LOCALES = ["uz", "ru", "en"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "uz";

export function isLocale(x: string): x is Locale {
  return (LOCALES as readonly string[]).includes(x);
}

/** Obyektdan joriy tildagi maydonni oladi: pick(obj, "title", "ru") -> obj.title_ru || obj.title_uz */
export function pick(obj: Record<string, any> | null | undefined, field: string, lang: Locale): string {
  if (!obj) return "";
  return obj[`${field}_${lang}`] || obj[`${field}_uz`] || obj[`${field}_en`] || obj[`${field}_ru`] || "";
}

