const DICTS: Record<Locale, Dict> = { uz, ru, en };

export function getDict(lang: string): Dict {
  return DICTS[isLocale(lang) ? lang : DEFAULT_LOCALE];
}

export function label(d: Dict, group: keyof Dict["labels"], value?: string | null): string {
  if (!value) return "";
  return (d.labels[group] as Record<string, string>)[value] || value;
}
